package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"reflect"
	"strconv"
	"strings"
	"text/template"

	"github.com/avfs/avfs"
	"github.com/avfs/avfs/vfs/osfs"
)

// collectorsPath is the import path prefix of the collector packages.
const collectorsPath = "github.com/osapi-io/gohai/pkg/gohai/collectors/"

// builtin is one Facts field that holds a collector's result.
type builtin struct {
	Field string
	Name  string
	Pkg   string
	Path  string
	Alias bool
}

// readBuiltins parses the Facts struct in src and returns its collector
// fields, in the order of the struct.
func readBuiltins(
	src []byte,
) ([]builtin, error) {
	file, err := parser.ParseFile(token.NewFileSet(), "facts.go", src, 0)
	if err != nil {
		return nil, fmt.Errorf("parse facts: %w", err)
	}

	paths := map[string]string{}
	for _, spec := range file.Imports {
		p, _ := strconv.Unquote(spec.Path.Value)
		name := p[strings.LastIndex(p, "/")+1:]
		if spec.Name != nil {
			name = spec.Name.Name
		}
		paths[name] = p
	}

	var st *ast.StructType
	ast.Inspect(file, func(n ast.Node) bool {
		if ts, ok := n.(*ast.TypeSpec); ok && ts.Name.Name == "Facts" {
			st, _ = ts.Type.(*ast.StructType)
		}
		return st == nil
	})
	if st == nil {
		return nil, fmt.Errorf("facts: no Facts struct")
	}

	var out []builtin
	for _, f := range st.Fields.List {
		b, ok := fieldBuiltin(f, paths)
		if ok {
			out = append(out, b)
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("facts: no collector fields")
	}

	return out, nil
}

// fieldBuiltin returns the collector of a Facts field. It is false for a
// field that is not a *pkg.Info of a collector package.
func fieldBuiltin(
	f *ast.Field,
	paths map[string]string,
) (builtin, bool) {
	star, ok := f.Type.(*ast.StarExpr)
	if !ok || len(f.Names) != 1 || f.Tag == nil {
		return builtin{}, false
	}
	sel, ok := star.X.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Info" {
		return builtin{}, false
	}
	pkg, ok := sel.X.(*ast.Ident)
	if !ok || !strings.HasPrefix(paths[pkg.Name], collectorsPath) {
		return builtin{}, false
	}
	tag, _ := strconv.Unquote(f.Tag.Value)
	name, _, _ := strings.Cut(reflect.StructTag(tag).Get("json"), ",")

	return builtin{
		Field: f.Names[0].Name,
		Name:  name,
		Pkg:   pkg.Name,
		Path:  paths[pkg.Name],
		Alias: !strings.HasSuffix(paths[pkg.Name], "/"+pkg.Name),
	}, true
}

// out is the template of builtins.gen.go.
var out = template.Must(
	template.New("builtins").Parse(`// Code generated by pkg/gohai/gen from facts.go. DO NOT EDIT.

package gohai

import (
	"github.com/osapi-io/gohai/internal/collector"
{{- range .}}
	{{if .Alias}}{{.Pkg}} {{end}}"{{.Path}}"
{{- end}}
	"github.com/osapi-io/gohai/pkg/gohai/source"
)

// builtinCollectors returns the built-in collectors to register, each
// reading the host through src. The cloud collectors also read their
// provider's metadata service, through src.HTTP.
func builtinCollectors(
	src source.Sources,
) []collector.Collector {
	return []collector.Collector{
{{- range .}}
		{{.Pkg}}.NewWith(src),
{{- end}}
	}
}

// set assigns the result of a single collector into the correct typed
// field on f. It is false when the name is unknown or the result is not
// the name's type, so the caller can record the result as an error.
func (f *Facts) set(
	name string,
	result any,
) bool {
	switch name {
{{- range .}}
	case "{{.Name}}":
		if v, ok := result.(*{{.Pkg}}.Info); ok {
			f.{{.Field}} = v
			return true
		}
{{- end}}
	}
	return false
}
`),
)

// generate reads the Facts struct from factsPath and writes the built-in
// collector list and the Facts setter to outPath.
func generate(
	fs avfs.VFS,
	factsPath string,
	outPath string,
) error {
	src, err := fs.ReadFile(factsPath)
	if err != nil {
		return fmt.Errorf("read facts: %w", err)
	}
	bs, err := readBuiltins(src)
	if err != nil {
		return err
	}

	var buf bytes.Buffer
	if err := out.Execute(&buf, bs); err != nil {
		return fmt.Errorf("render: %w", err)
	}
	code, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	if err := fs.WriteFile(outPath, code, 0o644); err != nil {
		return fmt.Errorf("write: %w", err)
	}

	return nil
}

func main() {
	factsPath := flag.String("facts", "../facts.go", "the file that holds the Facts struct")
	outPath := flag.String("out", "../builtins.gen.go", "the file to write")
	flag.Parse()

	if err := generate(osfs.NewWithNoIdm(), *factsPath, *outPath); err != nil {
		fmt.Fprintf(os.Stderr, "generate %s: %v\n", *outPath, err)
		os.Exit(1)
	}

	fmt.Printf("wrote %s\n", *outPath)
}
